const express = require('express');
const http = require('http');
const { Server } = require('socket.io');
const crypto = require('crypto');
const path = require('path');

const app = express();
const server = http.createServer(app);
const io = new Server(server, { cors: { origin: false }, pingInterval: 10000, pingTimeout: 20000 });
const PORT = Number(process.env.PORT) || 3000;
const MAX_PLAYERS = 8, MIN_PLAYERS = 2, LEVEL_LENGTH = 2600, TRACK_STEP = 20, RACE_LIMIT_MS = 900000;
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
function trackCenter(z, level) {
  const segment = Math.max(0, Math.min(Math.floor(z / TRACK_STEP), LEVEL_LENGTH / TRACK_STEP));
  const t = z / TRACK_STEP;
  const offset = i => { const difficulty = Math.min(Math.max(level - 1, 0) * 0.55, 7); const v = Math.sin((i + level * 17) * 1.731) * (10 + difficulty) + Math.sin((i + level * 7) * .713) * (6 + difficulty * 0.55); return Math.max(-24, Math.min(24, v)); };
  const a = offset(segment), b = offset(Math.min(segment + 1, LEVEL_LENGTH / TRACK_STEP));
  return a + (b - a) * (t - segment);
}
const rooms = new Map();
app.use(express.static(path.join(__dirname, 'public')));
app.get('/health', (_req, res) => res.json({ ok: true, rooms: rooms.size }));

const cleanName = (s) => String(s || 'Racer').replace(/[<>]/g, '').replace(/\s+/g, ' ').trim().slice(0, 16) || 'Racer';
const cleanCode = (s) => String(s || '').toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 5);
const makeCode = () => { let c; do { c = crypto.randomBytes(3).toString('hex').slice(0, 5).toUpperCase(); } while (rooms.has(c)); return c; };
// Match the decorative building layout generated by the client. Buildings are
// server-authoritative solid obstacles, not just scenery.
function generateBuildings() {
  let seed = 713;
  const rand = () => { seed = (seed * 16807) % 2147483647; return (seed - 1) / 2147483646; };
  const buildings = [];
  for (const side of [-1, 1]) {
    for (let z = 10; z < LEVEL_LENGTH; z += 36) {
      const w = 5 + rand() * 8;
      const h = 10 + rand() * 30;
      const d = 6 + rand() * 8;
      const x = side * (42 + rand() * 12);
      const bz = z + rand() * 5;
      buildings.push({ x, z: bz, w, d });
    }
  }
  return buildings;
}
const BUILDINGS = generateBuildings();
function collidesWithBuilding(x, z, heading = 0) {
  // SAT (separating-axis test): oriented car rectangle vs each building rectangle.
  // Car dimensions are intentionally close to the visible vehicle mesh.
  const carHalfW = 1.05, carHalfL = 2.0;
  const fx = Math.sin(heading), fz = Math.cos(heading);
  const rx = Math.cos(heading), rz = -Math.sin(heading);
  for (const b of BUILDINGS) {
    const dx = x - b.x, dz = z - b.z;
    const bx = b.w / 2, bz = b.d / 2;
    const carOnX = carHalfW * Math.abs(rx) + carHalfL * Math.abs(fx);
    const carOnZ = carHalfW * Math.abs(rz) + carHalfL * Math.abs(fz);
    if (Math.abs(dx) >= bx + carOnX || Math.abs(dz) >= bz + carOnZ) continue;
    const distRight = Math.abs(dx * rx + dz * rz);
    const buildingRight = bx * Math.abs(rx) + bz * Math.abs(rz);
    if (distRight >= carHalfW + buildingRight) continue;
    const distForward = Math.abs(dx * fx + dz * fz);
    const buildingForward = bx * Math.abs(fx) + bz * Math.abs(fz);
    if (distForward < carHalfL + buildingForward) return b;
  }
  return null;
}

// Barriers are solid, low rectangular obstacles. Use the same oriented-car
// footprint as building collision so the car cannot drive through or over them.
function collidesWithBarrier(x, z, heading = 0, items = []) {
  const carHalfW = 1.05, carHalfL = 2.0;
  const fx = Math.sin(heading), fz = Math.cos(heading);
  const rx = Math.cos(heading), rz = -Math.sin(heading);
  for (const item of items) {
    if (item.type !== 'barrier') continue;
    const dx = x - item.x, dz = z - item.z;
    const bx = 1.7, bz = 0.4;
    const carOnX = carHalfW * Math.abs(rx) + carHalfL * Math.abs(fx);
    const carOnZ = carHalfW * Math.abs(rz) + carHalfL * Math.abs(fz);
    if (Math.abs(dx) >= bx + carOnX || Math.abs(dz) >= bz + carOnZ) continue;
    const distRight = Math.abs(dx * rx + dz * rz);
    const barrierRight = bx * Math.abs(rx) + bz * Math.abs(rz);
    if (distRight >= carHalfW + barrierRight) continue;
    const distForward = Math.abs(dx * fx + dz * fz);
    const barrierForward = bx * Math.abs(fx) + bz * Math.abs(fz);
    if (distForward < carHalfL + barrierForward) return item;
  }
  return null;
}
function collidesWithSolid(x, z, heading, items) {
  return collidesWithBuilding(x, z, heading) || collidesWithBarrier(x, z, heading, items);
}

function generateItems(level) {
  // Deterministic per-level layout: pickups and hazards are generated server-side.
  let seed = (level * 7919 + 104729) % 2147483647;
  const rand = () => { seed = (seed * 16807) % 2147483647; return (seed - 1) / 2147483646; };
  const items = []; let id = 0;
  for (let z = 34; z < LEVEL_LENGTH - 22; z += 13) {
    const center = trackCenter(z, level);
    if (rand() < 0.72) {
      const lane = [-7, 0, 7][Math.floor(rand() * 3)];
      items.push({ id: `L${level}-C${id++}`, type: rand() < 0.18 ? 'nitro' : 'coin', x: center + lane, z, collectedBy: [] });
    }
    if (z > 70 && rand() < Math.min(0.34 + level * 0.018, 0.68)) {
      const lane = [-8, -4, 4, 8][Math.floor(rand() * 4)];
      items.push({ id: `L${level}-H${id++}`, type: rand() < 0.48 ? 'barrier' : 'mine', x: center + lane, z: z + 5, hitBy: [] });
    }
  }
  return items;
}
function resetLevel(room) {
  room.items = generateItems(room.level); room.raceStartedAt = null;
  for (const [i, p] of [...room.players.values()].entries()) {
    p.x = trackCenter(0, room.level) + (i - (room.players.size - 1) / 2) * 2.4; p.z = 2; p.heading = 0; p.speed = 0;
    p.lap = 0; p.checkpoint = 0; p.distance = 0; p.progress = 0; p.finished = false; p.finishTime = null; p.nitro = 100; p.ready = true; p.controls = {}; p.lastUpdate = Date.now(); p.coins = p.coins || 0; p.levelCoins = 0; p.hits = 0; p.driftScore = 0;
  }
}
function snapshot(room) {
  return {
    code: room.code, hostId: room.hostId, status: room.status, countdownAt: room.countdownAt, startedAt: room.startedAt, level: room.level, levelLength: LEVEL_LENGTH, raceElapsed: room.startedAt ? Math.max(0, Date.now() - room.startedAt) : 0, items: (room.items || []).map(i => ({ ...i, hitBy: i.hitBy ? [...i.hitBy] : undefined })),
    players: [...room.players.values()].map(p => ({
      id: p.id, name: p.name, color: p.color, ready: p.ready, x: p.x, z: p.z,
      heading: p.heading, speed: p.speed, lap: p.lap, checkpoint: p.checkpoint,
      progress: p.progress, finished: p.finished, finishTime: p.finishTime, nitro: p.nitro, coins: p.coins || 0, levelCoins: p.levelCoins || 0, hits: p.hits || 0, driftScore: p.driftScore || 0
    })).sort((a,b) => b.progress-a.progress)
  };
}
function broadcast(room) { io.to(room.code).emit('state', snapshot(room)); }
function leaveRoom(socket) {
  const code = socket.data.roomCode;
  if (!code || !rooms.has(code)) return;
  const room = rooms.get(code);
  room.players.delete(socket.id);
  socket.leave(code);
  socket.data.roomCode = null;
  if (!room.players.size) rooms.delete(code);
  else {
    if (room.status === 'countdown' && room.players.size < MIN_PLAYERS) { room.status = 'lobby'; room.countdownAt = null; }
    broadcast(room);
  }
}
function emitError(socket, message) { socket.emit('notice', { type: 'error', message }); }

io.on('connection', socket => {
  socket.data.roomCode = null;
  socket.on('createRoom', ({ name, level } = {}) => {
    leaveRoom(socket);
    const code = makeCode();
    const initialLevel = clamp(Math.floor(Number(level) || 1), 1, 50);
    const room = { code, hostId: socket.id, status: 'lobby', countdownAt: null, startedAt: null, raceStartedAt: null, level: initialLevel, players: new Map(), items: generateItems(initialLevel), createdAt: Date.now() };
    rooms.set(code, room);
    addPlayer(socket, room, name);
  });
  socket.on('joinRoom', ({ code, name } = {}) => {
    const normalized = cleanCode(code);
    const room = rooms.get(normalized);
    if (!room) return emitError(socket, 'Room not found. Check the code and try again.');
    if (room.players.size >= MAX_PLAYERS) return emitError(socket, 'That room is full (8 racers max).');
    if (room.status !== 'lobby') return emitError(socket, 'That race has already started.');
    leaveRoom(socket);
    addPlayer(socket, room, name);
  });
  socket.on('rejoinRoom', ({ code, name } = {}) => {
    const room = rooms.get(cleanCode(code));
    if (!room || room.status === 'finished') return emitError(socket, 'Could not reconnect to that race.');

    // Reclaim a disconnected slot instead of creating a duplicate racer.
    // Names are the available identity in this prototype; production should use a signed session token.
    const requestedName = cleanName(name);
    const entry = [...room.players.entries()].find(([, player]) =>
      player.disconnectedAt && player.name.toLowerCase() === requestedName.toLowerCase()
    );
    if (entry) {
      const [oldId, player] = entry;
      room.players.delete(oldId);
      player.id = socket.id;
      player.disconnectedAt = null;
      player.controls = {};
      player.lastUpdate = Date.now();
      room.players.set(socket.id, player);
      socket.join(room.code);
      socket.data.roomCode = room.code;
      socket.emit('joined', { code: room.code, id: socket.id, name: player.name, reconnected: true });
      broadcast(room);
      return;
    }
    if (room.players.size >= MAX_PLAYERS) return emitError(socket, 'That room is full (8 racers max).');
    if (room.status !== 'lobby') return emitError(socket, 'No disconnected racer with that name was found for this race.');
    addPlayer(socket, room, requestedName);
  });
  socket.on('setLevel', rawLevel => {
    const room = currentRoom(socket);
    if (!room || room.status !== 'lobby' || socket.id !== room.hostId) return;
    const level = clamp(Math.floor(Number(rawLevel) || 1), 1, 50);
    room.level = level;
    room.items = generateItems(level);
    for (const p of room.players.values()) { p.ready = false; }
    broadcast(room);
    io.to(room.code).emit('levelSelected', { level });
  });
  socket.on('setCarColor', value => {
    const room = currentRoom(socket); if (!room || room.status !== 'lobby') return;
    const p = room.players.get(socket.id); if (!p) return;
    const allowed = ['#00f5ff','#ff2bd6','#b6ff00','#ff8a00','#9b6bff','#ff3864','#32ffb4','#f8f7ff'];
    if (allowed.includes(value)) { p.color = value; broadcast(room); }
  });
  socket.on('setReady', value => {
    const room = currentRoom(socket);
    if (!room || !['lobby', 'countdown'].includes(room.status)) return;
    const p = room.players.get(socket.id); if (!p || p.disconnectedAt) return;
    p.ready = value === true;
    const everyoneReady = room.players.size >= MIN_PLAYERS && [...room.players.values()].every(x => x.ready && !x.disconnectedAt);
    if (everyoneReady && room.status === 'lobby') {
      room.status = 'countdown'; room.countdownAt = Date.now() + 3500;
      io.to(room.code).emit('countdown', { at: room.countdownAt });
    } else if (!everyoneReady && room.status === 'countdown') {
      room.status = 'lobby'; room.countdownAt = null;
      io.to(room.code).emit('countdownCancelled');
    }
    broadcast(room);
  });
  socket.on('nextLevel', () => {
    const room = currentRoom(socket);
    if (!room || room.status !== 'finished') return;
    room.level += 1; room.status = 'countdown'; room.countdownAt = Date.now() + 3500; room.startedAt = null;
    resetLevel(room);
    io.to(room.code).emit('levelStart', { level: room.level, theme: (room.level - 1) % 5 });
    io.to(room.code).emit('countdown', { at: room.countdownAt }); broadcast(room);
  });
  socket.on('input', raw => {
    const room = currentRoom(socket); if (!room || room.status !== 'racing') return;
    const p = room.players.get(socket.id); if (!p || p.finished) return;
    if (!raw || typeof raw !== 'object') return;
    // Server accepts only a small, explicit set of bounded controls.
    const now = Date.now();
    if (now - (p.lastInputAt || 0) < 12) return;
    p.lastInputAt = now;
    p.controls = {
      throttle: raw.throttle === true, brake: raw.brake === true,
      left: raw.left === true, right: raw.right === true,
      drift: raw.drift === true, boost: raw.boost === true
    };
  });
  socket.on('disconnect', () => {
    const code = socket.data.roomCode;
    if (code && rooms.has(code)) {
      const room = rooms.get(code), p = room.players.get(socket.id);
      if (p) { p.disconnectedAt = Date.now(); p.controls = {}; }
      // Keep the player slot briefly so a transient disconnect can recover.
      if (p) {
        const disconnectedId = socket.id;
        p.disconnectedAt = Date.now();
        p.controls = {};
        setTimeout(() => {
          const r = rooms.get(code), existing = r && r.players.get(disconnectedId);
          // A successful reconnect moves the player to a new socket ID, so this
          // timeout will no longer find (or accidentally remove) that player.
          if (existing && existing.disconnectedAt) {
            r.players.delete(disconnectedId);
            if (r.status === 'countdown' && (r.players.size < MIN_PLAYERS || ![...r.players.values()].every(x => x.ready && !x.disconnectedAt))) {
              r.status = 'lobby'; r.countdownAt = null; io.to(code).emit('countdownCancelled');
            }
            if (!r.players.size) rooms.delete(code); else broadcast(r);
          }
        }, 15000).unref();
      }
      if (room && room.status === 'countdown') {
        room.status = 'lobby'; room.countdownAt = null;
        io.to(code).emit('countdownCancelled');
      }
      socket.data.roomCode = null;
      if (room) broadcast(room);
    }
  });
});

function currentRoom(socket) {
  const code = socket.data.roomCode;
  return code ? rooms.get(code) : null;
}
function addPlayer(socket, room, name) {
  const colors = ['#00f5ff','#ff2bd6','#b6ff00','#ff8a00','#9b6bff','#ff3864','#32ffb4','#f8f7ff'];
  const idx = room.players.size;
  const p = {
    id: socket.id, name: cleanName(name), color: colors[idx % colors.length], ready: false, coins: 0, levelCoins: 0, hits: 0, driftScore: 0,
    x: trackCenter(0, room.level) + (idx - (room.players.size - 1) / 2) * 2.4, z: 2 + idx * 0.5, heading: 0, speed: 0,
    lap: 0, checkpoint: 0, distance: 0, progress: 0, finished: false, finishTime: null, nitro: 100,
    controls: {}, lastInputAt: 0, lastUpdate: Date.now()
  };
  room.players.set(socket.id, p); socket.join(room.code); socket.data.roomCode = room.code;
  socket.emit('joined', { code: room.code, id: socket.id, name: p.name });
  broadcast(room);
}
// Authoritative, bounded simulation. Client never submits position or lap progress.
setInterval(() => {
  const now = Date.now();
  for (const room of rooms.values()) {
    if (room.status === 'countdown' && now >= room.countdownAt) {
      room.status = 'racing'; room.startedAt = now; room.raceStartedAt = now; io.to(room.code).emit('raceStart', { at: now });
    }
    if (room.status === 'racing') {
      for (const p of room.players.values()) {
        if (p.finished) continue;
        const dt = clamp((now - p.lastUpdate) / 1000, 0, 0.05); p.lastUpdate = now;
        const c = p.controls || {};
        if (c.boost && p.nitro > 0 && p.speed > 4) { p.speed += 17 * dt; p.nitro = Math.max(0, p.nitro - 26 * dt); }
        else p.nitro = Math.min(100, p.nitro + 7 * dt);
        if (c.throttle) p.speed += 15.5 * dt;
        if (c.brake || c.drift) p.speed -= (c.drift ? 12 : 23) * dt;
        p.speed -= (c.throttle ? 0.7 : 4.3) * dt;
        p.speed = clamp(p.speed, -7, c.boost ? 48 : 38);
        const steer = (c.left ? 1 : 0) - (c.right ? 1 : 0);
        const grip = c.drift ? 0.42 : Math.max(0.72, 1 - Math.min(room.level - 1, 8) * 0.025);
        if (c.drift && Math.abs(p.speed) > 10 && Math.abs(steer) > 0) p.driftScore = (p.driftScore || 0) + Math.abs(p.speed) * dt;
        p.heading += steer * (0.7 + Math.min(Math.abs(p.speed) / 20, 1.5)) * grip * dt * (p.speed < 0 ? -1 : 1);
        const previousX = p.x, previousZ = p.z;
        const nextX = clamp(p.x + Math.sin(p.heading) * p.speed * dt, -48, 48);
        const nextZ = clamp(p.z + Math.cos(p.heading) * p.speed * dt, 0, LEVEL_LENGTH + 12);
        // Sweep each axis independently: the car collides edge-to-edge, loses
        // momentum, and can scrape/slide along a wall instead of ghosting through it.
        const hit = collidesWithSolid(nextX, nextZ, p.heading, room.items || []);
        if (!hit) { p.x = nextX; p.z = nextZ; }
        else {
          const hitX = collidesWithSolid(nextX, previousZ, p.heading, room.items || []);
          const hitZ = collidesWithSolid(previousX, nextZ, p.heading, room.items || []);
          if (!hitX && !hitZ) {
            // A diagonal corner contact can happen even when either axis alone
            // is clear. Resolve only the dominant axis to avoid clipping corners.
            if (Math.abs(nextX - previousX) > Math.abs(nextZ - previousZ)) p.x = nextX;
            else p.z = nextZ;
          } else {
            if (!hitX) p.x = nextX;
            if (!hitZ) p.z = nextZ;
          }
          if (hitX && hitZ) {
            p.x = previousX; p.z = previousZ;
            p.speed = -Math.min(2.2, Math.abs(p.speed) * 0.10);
            // Small rebound and deflection; never launch the car through a solid.
            p.heading += (p.x >= hit.x ? 1 : -1) * Math.min(0.12, Math.abs(p.speed) * 0.004);
          } else {
            // Side-scrapes lose speed but preserve the free axis so the racer can slide away.
            p.speed *= 0.42;
          }
          p.controls = { ...p.controls, throttle: false, boost: false };
          const hitNow = Date.now();
          if (!p.lastBuildingHitAt || hitNow - p.lastBuildingHitAt > 450) {
            p.lastBuildingHitAt = hitNow;
            const barrierHit = collidesWithBarrier(nextX, nextZ, p.heading, room.items || []) || collidesWithBarrier(p.x, p.z, p.heading, room.items || []);
            if (barrierHit) {
              if (!barrierHit.hitBy.includes(p.id)) {
                barrierHit.hitBy.push(p.id);
                p.nitro = Math.max(0, p.nitro - (12 + Math.min(room.level, 8)));
                p.hits = (p.hits || 0) + 1;
              }
              io.to(room.code).emit('hazardHit', { id: p.id, type: 'barrier', impact: Math.min(1, Math.abs(p.speed) / 20) });
            } else {
              io.to(room.code).emit('buildingHit', { id: p.id, impact: Math.min(1, Math.abs(p.speed) / 20), x: p.x, z: p.z });
            }
          }
        }
        const center = trackCenter(p.z, room.level);
        const trackHalfWidth = Math.max(8.5, 12.5 - Math.min(room.level - 1, 8) * 0.45);
        const onTrack = Math.abs(p.x - center) <= trackHalfWidth;
        if (!onTrack) p.speed *= Math.max(0, 1 - 3.2 * dt);
        // Collectibles and hazards are checked against authoritative server positions.
        for (const item of (room.items || [])) {
          if (Math.abs(item.z - p.z) > 2.5 || Math.abs(item.x - p.x) > 2.4) continue;
          if (item.type === 'coin' && !item.collectedBy.includes(p.id)) { item.collectedBy.push(p.id); p.coins = (p.coins || 0) + 1; p.levelCoins = (p.levelCoins || 0) + 1; io.to(p.id).emit('itemCollected', { type: 'coin' }); }
          else if (item.type === 'nitro' && !item.collectedBy.includes(p.id)) { item.collectedBy.push(p.id); p.nitro = Math.min(100, p.nitro + 38); io.to(p.id).emit('itemCollected', { type: 'nitro' }); }
          else if (['barrier', 'mine'].includes(item.type) && !item.hitBy.includes(p.id)) {
            item.hitBy.push(p.id);
            if (item.type === 'mine') {
              p.speed *= Math.max(0.42, 0.62 - Math.min(room.level - 1, 6) * 0.02);
              p.nitro = Math.max(0, p.nitro - (12 + Math.min(room.level, 8)));
              p.hits = (p.hits || 0) + 1;
              io.to(room.code).emit('hazardHit', { id: p.id, type: item.type });
            }
          }
        }
        p.distance += Math.max(0, p.speed) * dt;
        p.distance += Math.abs(p.speed) * dt;
        p.progress = Math.min(1, p.z / LEVEL_LENGTH) * 100;
        if (p.z >= LEVEL_LENGTH && Math.abs(p.x - trackCenter(LEVEL_LENGTH, room.level)) <= Math.max(10, 13.5 - Math.min(room.level - 1, 8) * 0.45)) {
          p.finished = true; p.finishTime = Math.max(0, now - room.startedAt);
          p.speed = 0; p.progress = 99999 - p.finishTime / 1000;
          io.to(room.code).emit('playerFinished', { id: p.id, name: p.name, time: p.finishTime });
        }
      }
      // Basic server-side car separation to discourage stacking/ramming exploits.
      const racers = [...room.players.values()].filter(p => !p.finished);
      for (let i=0;i<racers.length;i++) for (let j=i+1;j<racers.length;j++) {
        const a=racers[i], b=racers[j], dx=a.x-b.x, dz=a.z-b.z, d=Math.hypot(dx,dz);
        if (d > 0 && d < 2.6) { const push=(2.6-d)*0.035; a.x += dx/d*push; a.z += dz/d*push; b.x -= dx/d*push; b.z -= dz/d*push; a.speed*=0.995; b.speed*=0.995; }
      }
    }
    if (room.status === 'racing' && room.startedAt && now - room.startedAt >= RACE_LIMIT_MS) {
      // A timeout is still a deterministic race result: furthest progress wins, then finish time.
      for (const p of room.players.values()) if (!p.finished) { p.finished = true; p.speed = 0; p.finishTime = null; }
      room.status = 'finished'; io.to(room.code).emit('raceFinished', snapshot(room));
    } else if (room.status === 'racing' && [...room.players.values()].length > 0 && [...room.players.values()].every(p => p.finished)) {
      room.status = 'finished'; io.to(room.code).emit('raceFinished', snapshot(room));
    }
    broadcast(room);
  }
}, 50);

server.listen(PORT, () => console.log(`NEON RUSH online at http://localhost:${PORT}`));
